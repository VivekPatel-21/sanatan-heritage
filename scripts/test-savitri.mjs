import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {load} from 'cheerio';
const story=load(await readFile('dist/savitri-satyavan.html','utf8'));
const gallery=load(await readFile('dist/stories.html','utf8'));
const refs=load(await readFile('dist/sources.html','utf8'));
const book=JSON.parse(await readFile('src/data/scriptureCollections.json','utf8'));
const catalog=JSON.parse(await readFile('src/data/stories.json','utf8'));
assert.equal(story('main .tale-chapter').length,7,'Seven approved narrative chapters');
assert.equal(story('main .tale-hero-art img').length,1,'Only one story hero image');
assert.equal(story('main .tale-inline img').length,1,'Only one in-story illustration');
assert.equal(story('main img').length,2,'Exactly two images in the reader');
assert.equal(gallery('#story-savitri-satyavan img').length,1,'One separate gallery thumbnail');
const imageSources=[story('.tale-hero-art img').attr('src'),story('.tale-inline img').attr('src'),gallery('#story-savitri-satyavan img').attr('src')];
assert.equal(new Set(imageSources).size,3,'All three images are unique');
assert.ok(imageSources.every(s=>s.includes('savitri-satyavan-')));
assert.equal(story('.tale-contents nav a[href^="#"]').length,9,'Seven chapters and two supplementary stops');
assert.ok(story('#yama').text().includes('Her fourth request'));
assert.ok(story('#yama').text().includes('final request'));
assert.ok(story('#traditions').text().includes('Gita Press'));
assert.equal(gallery('#story-savitri-satyavan .collection-source a').attr('href'),'/sources.html#savitri-satyavan');
assert.equal(refs('#savitri-satyavan').length,1,'Unique primary source section');
assert.ok(refs('#savitri-satyavan').text().includes('1963–2019'));
assert.ok(book.categories.find(c=>c.id==='epics').collections.find(c=>c.id==='mahabharata').enabled);
assert.ok(catalog.savitri.collections.includes('mahabharata'));
const html=(await readFile('dist/savitri-satyavan.html','utf8'));
for(const filename of ['savitri-satyavan-meeting.webp','savitri-satyavan-yama.webp']) assert.ok(html.includes(filename));
console.log('Passed: complete Savitri reader, two unique internal illustrations, third catalog image, Mahabharata filter, references and metadata.');
