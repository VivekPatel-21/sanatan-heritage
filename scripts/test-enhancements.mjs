import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
const catalog=JSON.parse(await readFile('dist/data/reading-catalog.json','utf8'));
const stateScript=await readFile('src/assets/js/reading-state.js','utf8');
function state(){const dom=new JSDOM('<main></main>',{url:'https://sanatan.test/reading-library.html',runScripts:'outside-only'});dom.window.eval(stateScript);return dom;}
const first=state(),second=state();
first.window.SHReading.set('/hanuman-lanka.html',{saved:true,chapter:'court',bookmark:'court'});
second.window.SHReading.set('/hanuman-lanka.html',{completed:true});
const backup=JSON.parse(JSON.stringify(first.window.SHReading.exportBackup()));
const imported=second.window.SHReading.importBackup(backup,catalog);
assert.equal(imported.count,1);assert.equal(imported.persisted,true);
assert.equal(second.window.SHReading.get('/hanuman-lanka.html').saved,true);
assert.equal(second.window.SHReading.get('/hanuman-lanka.html').completed,true);
assert.equal(second.window.SHReading.get('/hanuman-lanka.html').bookmark,'court');
const before=JSON.stringify(second.window.SHReading.all());
const invalid={...backup,items:{...backup.items,'/not-a-site-page.html':{saved:true}}};
assert.throws(()=>second.window.SHReading.importBackup(invalid,catalog),/unrecognised/);
assert.equal(JSON.stringify(second.window.SHReading.all()),before,'Rejected imports are atomic');
assert.throws(()=>second.window.SHReading.importBackup({...backup,version:99},catalog),/version 1/);
assert.throws(()=>second.window.SHReading.importBackup({...backup,items:{'/hanuman-lanka.html':{chapter:'unknown-chapter'}}},catalog),/unrecognised chapter/);
second.window.SHReading.clear();assert.equal(Object.keys(second.window.SHReading.all()).length,0);
for(const dom of [first,second])dom.window.close();

const speechScript=await readFile('src/assets/js/read-aloud.js','utf8');
const dom=new JSDOM(await readFile('dist/shiva-halahala.html','utf8'),{url:'https://sanatan.test/shiva-halahala.html',runScripts:'outside-only'});
let spoken=[],paused=0,resumed=0,cancelled=0;
dom.window.SpeechSynthesisUtterance=class {constructor(text){this.text=text;}};
dom.window.speechSynthesis={getVoices:()=>[],speak:utterance=>spoken.push(utterance),pause:()=>paused++,resume:()=>resumed++,cancel:()=>cancelled++};
dom.window.eval(speechScript);
const buttons=[...dom.window.document.querySelectorAll('.listen-controls button')];
buttons[0].click();assert.equal(spoken.length,1);assert.match(spoken[0].text,/search for nectar/i);
buttons[1].click();assert.equal(paused,1);buttons[1].click();assert.equal(resumed,1);
buttons[2].click();assert.ok(cancelled>0);
const count=spoken.length;spoken[0].onend();assert.equal(spoken.length,count,'A cancelled callback cannot restart narration');
const select=dom.window.document.querySelector('#listen-chapter');select.value='2';select.dispatchEvent(new dom.window.Event('change'));buttons[0].click();assert.match(spoken.at(-1).text,/Halahala/);
dom.window.close();
const unsupported=new JSDOM(await readFile('dist/dhruva-hindi.html','utf8'),{runScripts:'outside-only'});unsupported.window.eval(speechScript);assert.ok(unsupported.window.document.querySelector('.read-aloud p[role="status"]').textContent.includes('उपलब्ध नहीं'));assert.ok(!unsupported.window.document.querySelector('.listen-controls'));unsupported.window.close();
console.log('Passed: library backup round-trip, non-destructive merge, atomic invalid imports, clear history, speech chapter selection/pause/stop, stale callback protection and unsupported-speech fallback.');
